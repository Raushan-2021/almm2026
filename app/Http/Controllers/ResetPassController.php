public function updatePassword(Request $request){
    
    if($request->isMethod('get')){
        /**************Start Audit trail************/
        $auditData = array('action_type'=>1,'description'=>' Changed password Page','user_type'=>0);
        $this->auditTrail($auditData);
        /**************End Audit trail************/
        return view('change-password');
    }
    $validatedData=$request->validate([

        'password'=>'required',
        'confirm-password'=>'required',
    ]);
    $password=$request->input('password');
    $confirmPassword=$request->input('confirm-password');
    
    if($password == $confirmPassword){
        $email = session('email');
        $user_type = session('user_type');
        if($user_type == 'MNRE'){
            $mnreData=Mnre::where('email',$email)->get()->first();
            if($mnreData != null){
                $mnre=Mnre::find($mnreData->id);
                $mnre->password = Hash::make($password);
                $mnre->update();
                /**************Start Audit trail************/
                $auditData = array('action_type'=>'3','description'=>'Password Update Successfuly','user_type'=>'1');
                $this->auditTrail($auditData);
                /**************End Audit trail************/
                //dd($mnre);
                return redirect('/login')->with('status' , 'Password Update Successfuly');
            }
        }else if($user_type == 'MANUFACTURER'){
            $get_manufacturer=User::where('email',$email)->get()->first();
            if($get_manufacturer != null){
                $user=User::find($get_manufacturer->id);
                $user->password= Hash::make($password);
                $user->update();
                /**************Start Audit trail************/
                $auditData = array('action_type'=>'3','description'=>' Changed password','user_type'=>'2');
                $this->auditTrail($auditData);
                /**************End Audit trail************/
                return redirect('/login')->with('status', 'Password Update Successfuly');
            }
        }else if($user_type == 'NISE'){
            $nise=Nise::where('email',$email)->get()->first();
            if($nise != null){
                $nisedata=Nise::find($nise->id);
                $nisedata->password= Hash::make($password);
                $nisedata->update();
                /**************Start Audit trail************/
                $auditData = array('action_type'=>'3','description'=>'User Changed password','user_type'=>'3');
                $this->auditTrail($auditData);
                /**************End Audit trail************/
                return redirect('/login')->with('message', 'Password Update Successfuly');
            }
        }
    }else{
        /**************Start Audit trail************/
        $auditData = array('action_type'=>'3','description'=>'User Changed passward','user_type'=>0);
        $this->auditTrail($auditData);
        /**************End Audit trail************/
        return redirect('/change-password')->with( "error" ,'Password not matched');
    }
   

